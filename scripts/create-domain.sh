EOF

echo -e "${GREEN}✅ Domain '${DOMAIN_NAME}' created successfully!${NC}"
echo -e "${BLUE}📂 Location: ${DOMAIN_PATH}${NC}"
echo -e ""
echo -e "${YELLOW}Next steps:${NC}"
echo -e "1. Edit ${DOMAIN_PATH}/README.md to describe the domain"
echo -e "2. Create entities in ${DOMAIN_PATH}/domain/entities/"
echo -e "3. Create value objects in ${DOMAIN_PATH}/domain/value-objects/"
echo -e "4. Create repository interfaces in ${DOMAIN_PATH}/domain/repositories/"
echo -e "5. Create use cases in ${DOMAIN_PATH}/application/use-cases/"
echo -e "6. Implement repositories in ${DOMAIN_PATH}/infrastructure/persistence/prisma/"
echo -e ""
echo -e "${BLUE}📚 See docs/MIGRATION_GUIDE.md for more details${NC}"

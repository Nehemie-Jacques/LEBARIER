EOF

# Créer un fichier template pour un use case
echo -e "${GREEN}⚡ Creating use case template...${NC}"
cat > "${DOMAIN_PATH}/application/use-cases/_use-case.template.ts" << 'EOF'
// ============================================
// DOMAIN - Use Case Name
// ============================================


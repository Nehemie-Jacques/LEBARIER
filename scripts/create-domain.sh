#!/bin/bash

# ============================================
# Script de génération d'un nouveau domaine DDD
# ============================================

# Couleurs pour les messages
GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# Vérifier que le nom du domaine est fourni
if [ -z "$1" ]; then
    echo -e "${YELLOW}Usage: ./scripts/create-domain.sh <domain-name>${NC}"
    echo -e "${YELLOW}Example: ./scripts/create-domain.sh user-management${NC}"
    exit 1
fi

DOMAIN_NAME=$1
DOMAIN_PATH="src/domains/${DOMAIN_NAME}"

echo -e "${BLUE}🏗️  Creating domain: ${DOMAIN_NAME}${NC}"

# Créer la structure de répertoires
echo -e "${GREEN}📁 Creating directory structure...${NC}"
mkdir -p "${DOMAIN_PATH}/domain/entities"
mkdir -p "${DOMAIN_PATH}/domain/value-objects"
mkdir -p "${DOMAIN_PATH}/domain/repositories"
mkdir -p "${DOMAIN_PATH}/domain/services"
mkdir -p "${DOMAIN_PATH}/domain/errors"

mkdir -p "${DOMAIN_PATH}/application/use-cases"
mkdir -p "${DOMAIN_PATH}/application/dto"
mkdir -p "${DOMAIN_PATH}/application/services"
mkdir -p "${DOMAIN_PATH}/application/events"

mkdir -p "${DOMAIN_PATH}/infrastructure/persistence/prisma"
mkdir -p "${DOMAIN_PATH}/infrastructure/persistence/mappers"
mkdir -p "${DOMAIN_PATH}/infrastructure/api"
mkdir -p "${DOMAIN_PATH}/infrastructure/messaging"

mkdir -p "${DOMAIN_PATH}/presentation/api/routes"
mkdir -p "${DOMAIN_PATH}/presentation/components"

# Créer le fichier README du domaine
echo -e "${GREEN}📝 Creating README...${NC}"
cat > "${DOMAIN_PATH}/README.md" << EOF
# ${DOMAIN_NAME^} Domain

## Description
[Add domain description here]

## Bounded Context
This domain is responsible for:
- [Responsibility 1]
- [Responsibility 2]
- [Responsibility 3]

## Entities
- [ ] Entity1
- [ ] Entity2

## Value Objects
- [ ] ValueObject1
- [ ] ValueObject2

## Use Cases
- [ ] UseCase1
- [ ] UseCase2

## Events
- [ ] Event1
- [ ] Event2

## Dependencies
- Depends on: [Other domains]
- Used by: [Other domains]

## Status
- [ ] Domain Layer
- [ ] Application Layer
- [ ] Infrastructure Layer
- [ ] Presentation Layer
- [ ] Tests

## Documentation
[Link to detailed documentation]
EOF

# Créer le fichier d'erreurs du domaine
echo -e "${GREEN}🚨 Creating domain errors...${NC}"
cat > "${DOMAIN_PATH}/domain/errors/${DOMAIN_NAME}.errors.ts" << 'EOF'
// ============================================
// DOMAIN - Domain Errors
// ============================================

import { DomainError } from '@/shared/errors/base.error';

export class EntityNotFoundError extends DomainError {
  constructor(id: string) {
    super(\`Entity with ID '\${id}' not found\`, 'ENTITY_NOT_FOUND', 404);
  }
}

// Add more domain-specific errors here
EOF

# Créer le fichier index du domaine
echo -e "${GREEN}📦 Creating index.ts...${NC}"
cat > "${DOMAIN_PATH}/index.ts" << EOF
// ============================================
// ${DOMAIN_NAME^^} DOMAIN - Exports
// ============================================

// Domain Layer
// export * from './domain/entities/...';
// export * from './domain/value-objects/...';
// export * from './domain/repositories/...';
export * from './domain/errors/${DOMAIN_NAME}.errors';

// Application Layer
// export * from './application/use-cases/...';
// export * from './application/dto/...';
// export * from './application/events/...';

// Infrastructure Layer
// export * from './infrastructure/persistence/prisma/...';
// export * from './infrastructure/persistence/mappers/...';
EOF

# Créer un fichier template pour une entité
echo -e "${GREEN}🎯 Creating entity template...${NC}"
cat > "${DOMAIN_PATH}/domain/entities/_entity.template.ts" << 'EOF'
// ============================================
// DOMAIN - Entity Name
// ============================================


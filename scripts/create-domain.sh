  constructor(private deps: Dependencies) {}

  async execute(dto: UseCaseDTO): Promise<Result<UseCaseResponseDTO>> {
    try {
      // 1. Validation
      
      // 2. Business logic
      
      // 3. Persistence
      
      // 4. Publish events
      
      // 5. Return response
      
      return success({
        // response data
